// WebSocket-ის Bidirectional Communication და Duplex Mode

// Bidirectional Communication ნიშნავს ორმხრივ კომუნიკაციას, სადაც Client-საც და Server-საც შეუძლიათ ნებისმიერ დროს გაუგზავნონ ერთმანეთს მონაცემები. ამისთვის არ არის საჭირო, რომ ერთი მხარე დაელოდოს მეორის მოთხოვნას.

// Duplex Mode ნიშნავს, რომ მონაცემების გაგზავნა და მიღება ორივე მიმართულებით ერთდროულად ხდება. ანუ Client-ს შეუძლია მონაცემების გაგზავნა მაშინ, როცა Server-იც პარალელურად აგზავნის მონაცემებს.

// როგორ მუშაობს?
// Client ამყარებს WebSocket კავშირს Server-თან.
// კავშირი ღია რჩება (Persistent Connection).
// Client და Server ნებისმიერ დროს ცვლიან ინფორმაციას.
// მონაცემების გაგზავნა და მიღება ერთდროულად შესაძლებელია.

// რატომ არის ეს მნიშვნელოვანი Real-Time აპლიკაციებისთვის?

// თუ გამოიყენება ჩვეულებრივი HTTP, კლიენტმა მუდმივად უნდა შეამოწმოს, ხომ არ არის ახალი მონაცემები (Polling).

// WebSocket-ში კი Server თავად აგზავნის განახლებებს მაშინვე, როცა ისინი გამოჩნდება.