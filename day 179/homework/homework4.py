# 4) დაწერეთ ციკლი, რომელშიც n ყოველ იტერაციაზე ორჯერ მცირდება. შეამოწმეთ n=64 და აჩვენეთ ცვლადის მნიშვნელობა თითოეულ ნაბიჯზე. დაითვალეთ იტერაციების რაოდენობა და ახსენით რატომ არის ალგორითმის დროითი სირთულე O(log n)

n = 64
count = 0

while n > 1:
    n = n // 2
    count += 1
    print(n)

print("Iterations:", count)

# როდესაც ციკლში ცვლადი ყოველ ნაბიჯზე ორჯერ მცირდება ან იზრდება, იტერაციების რაოდენობა ლოგარითმულად იცვლება და ალგორითმის დროითი სირთულე არის O(log n).