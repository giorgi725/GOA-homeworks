# 1) დაწერეთ რეკურსიული ფუნქცია reverse(s), რომელიც სტრიქონს შეაბრუნებს. შეამოწმეთ s="programming". ახსენით Base Case და Recursive Case, აჩვენეთ რეკურსიული გამოძახებები და განსაზღვრეთ დროითი სირთულე

def reverse(s):
    if len(s) == 0:
        return s
    return s[-1] + reverse(s[:-1])

print(reverse("programming"))

# დროითი სირთულე (Time Complexity)
# O(n²) — Python-ში სტრიქონის s[1:] და სტრიქონების გაერთიანება (+) ახალ სტრიქონებს ქმნის და სიმბოლოებს აკოპირებს. ეს ოპერაციები თითოეულ რეკურსიულ გამოძახებაზე სრულდება.

# სივრცითი სირთულე: O(n²) — რეკურსიული გამოძახებებისა და შუალედური სტრიქონების გამო.