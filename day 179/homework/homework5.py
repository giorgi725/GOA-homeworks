# 5) დაწერეთ lower_bound(A, x) ფუნქცია, რომელიც დალაგებულ მასივში იპოვის x-ზე არანაკლები პირველი ელემენტის ინდექსს. გამოიყენეთ A=[2, 2, 3, 3, 3, 5, 7, 7, 9], x=7. ამოხსენით ორობითი ძებნის გამოყენებით, აჩვენეთ თითოეული იტერაცია და განსაზღვრეთ დროითი სირთულე

def lower_bound(A, x):
    low = 0
    high = len(A)

    while low < high:
        mid = (low + high) // 2
        if A[mid] < x:
            low = mid + 1
        else:
            high = mid

    return low


A = [2, 2, 3, 3, 3, 5, 7, 7, 9]
x = 7

print(lower_bound(A, x))

# დროითი სირთულე
# O(log n) — რადგან ორობითი ძებნის დროს თითოეულ იტერაციაზე საძიებო არეალი დაახლოებით ორჯერ მცირდება.

# სივრცითი სირთულე: O(1), რადგან იტერაციული ორობითი ძებნა მხოლოდ რამდენიმე ცვლადს იყენებს