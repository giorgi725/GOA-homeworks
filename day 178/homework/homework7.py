# 7) დაწერეთ bubble_sort(A) ფუნქცია, რომელიც მასივს ზრდადობით დაალაგებს. გამოიყენეთ [7, 3, 11, 5, 2, 9, 4]. აჩვენეთ თითოეული გარე იტერაციის შედეგი და დაითვალეთ გაცვლების რაოდენობა. განსაზღვრეთ საუკეთესო, საშუალო და უარესი დროითი სირთულე

def bubble_sort(A):
    swaps = 0
    for i in range(len(A) - 1):
        for j in range(len(A) - 1 - i):
            if A[j] > A[j + 1]:
                A[j], A[j + 1] = A[j + 1], A[j]
                swaps += 1
        print(A)
    print("Swaps:", swaps)
    return A

A = [7, 3, 11, 5, 2, 9, 4]

print(bubble_sort(A))

# დროითი სირთულე (Time Complexity)
# - საუკეთესო შემთხვევა — O(n): თუ მასივი უკვე დალაგებულია და ვიყენებთ ოპტიმიზაციას, რომელიც გაცვლის გარეშე ციკლს აჩერებს.
# - საშუალო შემთხვევა — O(n²): ელემენტების შედარებების რაოდენობა კვადრატულად იზრდება.
# - უარესი შემთხვევა — O(n²): თუ მასივი უკუღმაა დალაგებული, საჭიროა ბევრი შედარება და გაცვლა.