# 1) დაწერეთ რეკურსიული ფუნქცია multiply(a, b), რომელიც ორი არაუარყოფითი მთელი რიცხვის ნამრავლს გამოთვლის მხოლოდ შეკრების გამოყენებით. შეამოწმეთ a=3, b=4. ახსენით Base Case და Recursive Case, განსაზღვრეთ დროითი სირთულე

def multiply(a, b):
    if b == 0:
        return 0
    return a + multiply(a, b - 1)


print(multiply(3, 4))


