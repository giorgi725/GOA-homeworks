# 2) დაწერეთ რეკურსიული ფუნქცია gcd(a, b), რომელიც ევკლიდეს ალგორითმით იპოვის ორი რიცხვის უდიდეს საერთო გამყოფს. გამოთვალეთ gcd(51, 27), აჩვენეთ თითოეული რეკურსიული გამოძახება და ახსენით გაჩერების პირობა

def gcd(a, b):
    if b == 0:
        return a
    return gcd(b, a % b)

print(gcd(51, 27))


# gcd(a,b)=gcd(b,a % b)