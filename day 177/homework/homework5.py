# 6) დაწერეთ find_max(arr) ფუნქცია, რომელიც მასივში მაქსიმალურ ელემენტს იპოვის max() ფუნქციის გარეშე. ახსენით ალგორითმის მუშაობა ნაბიჯ-ნაბიჯ, დაითვალეთ საჭირო შედარებების რაოდენობა n ელემენტიანი მასივისთვის და განსაზღვრეთ დროითი და სივრცითი სირთულე

def find_max(arr):
    max_num = arr[0]
    for num in arr:
        if max_num < num:
            max_num = num
    return max_num

arr = [5, 12, 3, 25, 8]

print(find_max(arr))

