# 3) დაწერეთ რეკურსიული ფუნქცია sum_digits(n), რომელიც დააბრუნებს რიცხვის ციფრების ჯამს. მაგალითად sum_digits(1234) უნდა აბრუნებდეს 10-ს. ახსენით როგორ მუშაობს რეკურსია, მიუთითეთ Base Case და განსაზღვრეთ დროითი სირთულე

def sum_digits(n):
    if n == 0: 
        return 0
    return n % 10 + sum_digits(n // 10)

print(sum_digits(1234))  

# რეკურსია არის მეთოდი, როდესაც ფუნქცია საკუთარ თავს ხელახლა იძახებს.
# - Base Case: if n == 0 – გაჩერების პირობა. როდესაც რიცხვი 0 ხდება, ფუნქცია აბრუნებს 0-ს.
# - Recursive Case: n % 10 + sum_digits(n // 10) – იღებს ბოლო ციფრს და ამატებს დარჩენილი რიცხვის ციფრების ჯამს.

# დროითი სირთულე (Time Complexity)
# O(log n) – რადგან ყოველ გამოძახებაზე რიცხვი 10-ჯერ მცირდება (ერთ ციფრს ვშლით).

# Space Complexity – O(log n) – რეკურსიული გამოძახებები ინახება Call Stack-ში.