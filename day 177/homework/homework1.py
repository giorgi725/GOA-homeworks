# რეკურსია არის პროგრამირების მეთოდი, როდესაც ფუნქცია საკუთარ თავს იძახებს, რათა ამოცანა პატარა ნაწილებად დაყოს და ამოხსნას.

# რეკურსიას აქვს ორი მთავარი ნაწილი:
# - Base Case – გაჩერების პირობა. განსაზღვრავს, როდის უნდა შეწყდეს ფუნქციის გამოძახება.
# - Recursive Case – რეკურსიული ნაწილი, სადაც ფუნქცია საკუთარ თავს ხელახლა იძახებს.
# 2. Factorial ფუნქცია
# რიცხვის ფაქტორიალი არის ყველა დადებითი მთელი რიცხვის ნამრავლი 1-დან ამ რიცხვამდე.

def factorial(n):
    if n == 0 or n == 1:
        return 1
    return n * factorial(n - 1)


print(factorial(5))

# დროითი და სივრცითი სირთულე
# - Time Complexity – O(n): ფუნქცია გამოიძახება n-ჯერ, ამიტომ დროითი სირთულე ხაზოვანია.
# - Space Complexity – O(n): ყოველი რეკურსიული გამოძახება იკავებს მეხსიერებას Call Stack-ში, ამიტომ სივრცითი სირთულეც ხაზოვანია.