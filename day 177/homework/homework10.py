# 11) შეადარეთ Selection Sort და Insertion Sort. ახსენით როგორ ირჩევენ ელემენტების სწორ პოზიციებს, რომელს სჭირდება მეტი შედარება და რომელი მუშაობს უკეთ თითქმის დალაგებულ მასივებზე. ორივე ალგორითმით დაალაგეთ [4, 1, 3, 2, 5] და შეადარეთ შესრულებული ოპერაციების რაოდენობა

# Selection Sort:
# - ეძებს ყველაზე პატარა ელემენტს დაუხარისხებელ ნაწილში.
# - პოულობს მინიმუმს და მიმდინარე პოზიციაზე აყენებს.
# - ყოველ ეტაპზე მინიმუმს ცვლის ადგილს მიმდინარე ელემენტთან.
# Insertion Sort:
# - იღებს შემდეგ ელემენტს (key).
# - ადარებს მარცხენა მხარეს არსებულ ელემენტებს.
# - უფრო დიდ ელემენტებს მარჯვნივ წევს და key-ს სწორ ადგილას სვამს.

# რომელი აკეთებს მეტ შედარებას?/
# - Selection Sort ყოველთვის აკეთებს ერთნაირი რაოდენობის შედარებებს: n(n-1)/2
# - Insertion Sort შედარებების რაოდენობა დამოკიდებულია მასივის მდგომარეობაზე. თითქმის დალაგებულ მასივზე ნაკლებ შედარებას აკეთებს.